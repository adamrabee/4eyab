#!/usr/bin/env bash
# Local Supabase stack control for HISSATI (development/testing only).
#   up     generate local secrets if missing, start stack, apply migrations, write .env.local
#   down   stop stack (data kept)
#   reset  stop stack, DELETE local data volumes, start fresh
#   migrate apply pending migrations only
# Contacts no remote service other than Docker Hub for image pulls.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SB="$ROOT/supabase"
ENVF="$SB/.env"
COMPOSE=(docker compose -f "$SB/docker-compose.yml" --env-file "$ENVF")

ensure_docker() {
  if ! docker info >/dev/null 2>&1; then
    echo "starting docker daemon..."
    (dockerd >/tmp/dockerd.log 2>&1 &)
    for _ in $(seq 1 30); do docker info >/dev/null 2>&1 && return; sleep 1; done
    echo "docker daemon did not start" >&2; exit 1
  fi
}

gen_env() {
  [ -f "$ENVF" ] && return
  echo "generating local secrets in supabase/.env (gitignored)"
  node - "$ENVF" <<'NODE'
const crypto = require("crypto"), fs = require("fs");
const b64u = (b) => Buffer.from(b).toString("base64url");
const secret = crypto.randomBytes(40).toString("hex");
const sign = (role) => {
  const h = b64u(JSON.stringify({ alg: "HS256", typ: "JWT" }));
  const now = Math.floor(Date.now() / 1000);
  const p = b64u(JSON.stringify({ role, iss: "supabase-local", iat: now, exp: now + 10 * 365 * 24 * 3600 }));
  const s = crypto.createHmac("sha256", secret).update(`${h}.${p}`).digest("base64url");
  return `${h}.${p}.${s}`;
};
fs.writeFileSync(process.argv[2], [
  `POSTGRES_PASSWORD=${crypto.randomBytes(24).toString("hex")}`,
  `JWT_SECRET=${secret}`,
  `ANON_KEY=${sign("anon")}`,
  `SERVICE_ROLE_KEY=${sign("service_role")}`,
  "",
].join("\n"), { mode: 0o600 });
NODE
}

psql_db() { # run psql against local db as postgres (same role migrations use on hosted Supabase)
  # shellcheck disable=SC1090
  source "$ENVF"
  PGPASSWORD="$POSTGRES_PASSWORD" psql -v ON_ERROR_STOP=1 -q -h 127.0.0.1 -p 54322 -U postgres -d postgres "$@"
}

wait_ready() {
  echo -n "waiting for services"
  for _ in $(seq 1 90); do
    if curl -fs http://127.0.0.1:54321/auth/v1/health >/dev/null 2>&1 \
       && curl -fs http://127.0.0.1:54321/storage/v1/status >/dev/null 2>&1 \
       && psql_db -tAc "select 1 from information_schema.tables where table_schema='storage' and table_name='buckets'" | grep -q 1; then
      echo " ready"; return
    fi
    echo -n "."; sleep 2
  done
  echo; echo "services did not become ready" >&2; "${COMPOSE[@]}" ps; exit 1
}

migrate() {
  psql_db -c "create schema if not exists supabase_migrations; create table if not exists supabase_migrations.schema_migrations (version text primary key, applied_at timestamptz default now());"
  for f in "$SB"/migrations/*.sql; do
    [ -e "$f" ] || continue
    v="$(basename "$f")"
    if [ -z "$(psql_db -tAc "select 1 from supabase_migrations.schema_migrations where version='$v'")" ]; then
      echo "applying $v"
      psql_db -1 -f "$f"
      psql_db -c "insert into supabase_migrations.schema_migrations(version) values ('$v')"
    fi
  done
}

write_app_env() {
  # shellcheck disable=SC1090
  source "$ENVF"
  local f="$ROOT/.env.local"
  local keep=""
  [ -f "$f" ] && keep="$(grep -E '^(ANTHROPIC_API_KEY|AI_PROVIDER|ANTHROPIC_MODEL)=' "$f" || true)"
  {
    echo "# Generated by scripts/supabase-local.sh — LOCAL DEV ONLY, gitignored."
    echo "NEXT_PUBLIC_SUPABASE_URL=http://localhost:54321"
    echo "NEXT_PUBLIC_SUPABASE_ANON_KEY=$ANON_KEY"
    echo "SUPABASE_SERVICE_ROLE_KEY=$SERVICE_ROLE_KEY"
    echo "DATABASE_URL=postgres://postgres:$POSTGRES_PASSWORD@127.0.0.1:54322/postgres"
    if [ -n "$keep" ]; then echo "$keep"; else echo "AI_PROVIDER=mock"; fi
  } > "$f"
  chmod 600 "$f"
  echo "wrote .env.local"
}

case "${1:-up}" in
  up) ensure_docker; gen_env; mkdir -p "$SB/volumes/data" "$SB/volumes/storage"; "${COMPOSE[@]}" up -d; wait_ready; migrate; write_app_env ;;
  down) ensure_docker; "${COMPOSE[@]}" down ;;
  reset) ensure_docker; gen_env; "${COMPOSE[@]}" down -v || true; rm -rf "$SB/volumes/data" "$SB/volumes/storage"; exec "$0" up ;;
  migrate) migrate ;;
  psql) shift; psql_db "$@" ;;
  *) echo "usage: $0 up|down|reset|migrate|psql"; exit 1 ;;
esac
